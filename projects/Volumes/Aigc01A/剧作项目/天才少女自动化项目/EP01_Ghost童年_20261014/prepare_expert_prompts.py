def create(group, duration, beat, cycle, flow, header_roles, shots, extra=''):
    bindings = []
    def anchor(a, asset, category):
        bindings.append({'anchor': a, 'filename': asset, 'category': category})
        return a + asset
    header_lines = [anchor(group+'组头场景结构锁', SCENE, '场景')]
    for name, asset in header_roles:
        header_lines.append(anchor(group+'组头'+name+'身份锁', asset, '角色'))
    header_lines.append(anchor(group+'组头成年Elena旁白音色锁', VOICE, '角色'))
    txt = f'【组头｜EP01-{group}｜固定画质词与光影基调】\n{FIXED}\n\n'
    txt += f'光影基调（Lighting Tone）：{COMMON_LIGHT}\n'
    txt += f'节奏结构（Beat Structure）：组型：自主程序追捕闪回｜{len(shots)}镜｜共{duration:.1f}s；{beat}所有台词入点是英文朗读估算，未声称音频实测。\n'
    txt += f'景别循环（Shot Size Cycle）：{cycle}\n'
    txt += f'视觉动线（Visual Flow）：{flow}\n'
    txt += f'引用锁／项目参数：九梦2.5 Pro／480P，9:16，{duration:.1f}s。固定画质段中的85mm为基础质感描述，实际摄影依各shot焦段执行。所有角色只锁身份、原发型、体型和本次服装；场景只锁真实桌椅、双屏、门、玻璃、服务器和指定英文标识，不继承棚拍背景与无关构图。' + extra + '\n'
    txt += '原生组头锁：' + '；'.join(header_lines) + '。\n'
    txt += f'空间锁：{COMMON_LAYOUT}\n\n'
    for n, s in enumerate(shots, 1):
        txt += f'【shot {n}｜{s["title"]}｜{s["size"]}（Shot Size）｜{s["angle"]}（Angle）｜{s["move"]}（Camera Movement）｜{s["lens"]}（Focal Length）｜duration: {s["duration"]:.1f}s】\n'
        vals = list(s['fields'])
        prefix = anchor(group+f'镜{n}场景结构锁', SCENE, '场景') + '；'
        for name, asset in s.get('roles', []):
            prefix += anchor(group+f'镜{n}'+name+'身份锁', asset, '角色') + '；'
        vals[2] = prefix + vals[2]
        assert len(vals) == len(FIELD_LABELS)
        for label, val in zip(FIELD_LABELS, vals):
            txt += label + '：' + val + '\n'
        txt += '\n'
    (OUT / (group+'.txt')).write_text(txt)
    (OUT / (group+'.anchors.json')).write_text(json.dumps(bindings, ensure_ascii=False, indent=2)+'\n')
    return {'group':group,'characters':len(txt),'duration':duration,'shots':len(shots),'bindings':len(bindings)}

