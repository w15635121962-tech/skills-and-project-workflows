patches = []
spans = {}
labels = ('时长', '环境氛围', '景别', '拍摄角度', '摄像机运动', '人物角色和运动', '人物表演', '画面内容')

def field(n, shot, label):
    t = texts[n]
    if shot == 0:
        a = t.index('场景：')
        b = t.index('以下所有Shot', a)
        return t[a:b].rstrip()
    m = re.search(rf'^Shot{shot:02}:', t, re.M)
    assert m, (n, shot)
    start = m.end()
    nxt = re.search(r'^Shot\d+:', t[start:], re.M)
    end = start + nxt.start() if nxt else len(t)
    part = t[start:end]
    a = re.search(rf'^{label}：', part, re.M)
    assert a, (n, shot, label)
    rest = part[a.end():]
    b = re.search(r'^(?:' + '|'.join(labels) + r')：', rest, re.M)
    return part[a.start():a.end() + b.start() if b else len(part)].rstrip()

def add(n, shot, label, change, reason):
    old = field(n, shot, label)
    new = change(old) if callable(change) else change
    assert old != new, (n, shot, label, 'unchanged')
    assert texts[n].count(old) == 1, (n, shot, label, 'nonunique')
    key = (n, shot, label)
    assert key not in spans
    spans[key] = True
    patches.append(dict(group=f'G{n:02}', old=old, new=new, reason=reason))

def sub(*pairs):
    def fn(s):
        for old, new in pairs:
            assert s.count(old) == 1, (old, s)
            s = s.replace(old, new)
        return s
    return fn

