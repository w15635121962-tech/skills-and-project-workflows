def english_quotes(t):
    return [s for s in re.findall(r'“([^”]+)”', t) if re.search(r'[A-Za-z]', s)]

validated = []
for n, original in texts.items():
    changed = original
    for p in patches:
        if p['group'] == f'G{n:02}':
            assert changed.count(p['old']) == 1, (n, p['reason'], 'sequential match failed')
            changed = changed.replace(p['old'], p['new'], 1)
    assert english_quotes(original) == english_quotes(changed), (n, english_quotes(original), english_quotes(changed))
    for label in ('时长', '景别', '摄像机运动'):
        pattern = rf'^{label}：.*?(?=^(?:' + '|'.join(labels) + r')：|^Shot\d+:|\Z)'
        assert re.findall(pattern, original, re.M | re.S) == re.findall(pattern, changed, re.M | re.S), (n, label)
    mentions0 = re.findall(r'@\s*([^\n]+)', original)
    mentions1 = re.findall(r'@\s*([^\n]+)', changed)
    assert mentions0 == mentions1, (n, 'asset changed')
    assert re.findall(r'^Shot\d+:', original, re.M) == re.findall(r'^Shot\d+:', changed, re.M)
