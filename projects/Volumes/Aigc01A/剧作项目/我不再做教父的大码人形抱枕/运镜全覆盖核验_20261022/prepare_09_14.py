patches = []
motion_keys = set()
for p in range(9,15):
    prompt = data['groups'][p-1]['prompt']
    headers = list(re.finditer(r'^【shot\s+(\d+)｜.*$',prompt,re.M))
    for j,match in enumerate(headers):
        n = int(match.group(1)); key=(p,n)
        title = match.group(0)
        end = headers[j+1].start() if j+1<len(headers) else len(prompt)
        section = prompt[match.end():end]
        old_camera = next(line for line in section.splitlines() if line.startswith('镜头：'))
        movement,new_camera,reason = MOVES[key]
        new_title = re.sub(r'运镜（Camera Movement）：[^｜]+', '运镜（Camera Movement）：'+movement, title)
        assert new_title != title
        patches.append({'position':p,'unit':1,'shot':n,'old':title,'new':new_title,'reason':reason})
        patches.append({'position':p,'unit':1,'shot':n,'old':old_camera,'new':new_camera,'reason':reason})
        motion_keys.add(key)
assert motion_keys == set(MOVES)

for p in range(9,15):
    original = data['groups'][p-1]['prompt']
    revised=original
    for patch in patches:
        if patch['position']!=p: continue
        assert revised.count(patch['old'])==1,(p,patch['shot'])
        revised=revised.replace(patch['old'],patch['new'])
    for prefix in ['画面：','音频（Audio）：','微表演（Micro-Performance）：','对白反应（Dialogue Reaction）：','负面提示词（Negative Prompt）：']:
        assert re.findall('^'+re.escape(prefix)+'.*$',original,re.M)==re.findall('^'+re.escape(prefix)+'.*$',revised,re.M)
    assert re.findall(r'duration:\s*[\d.]+s',original)==re.findall(r'duration:\s*[\d.]+s',revised)
    assert re.findall(r'§ASSET:[^§]+§',original)==re.findall(r'§ASSET:[^§]+§',revised)
    assert not re.search(r'运镜（Camera Movement）：固定|^镜头：.*(?:固定|位置与轴线不变)',revised,re.M)
    assert len(revised)<15000

