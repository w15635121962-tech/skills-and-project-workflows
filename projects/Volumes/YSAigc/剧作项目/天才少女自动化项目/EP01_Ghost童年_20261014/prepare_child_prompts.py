def shot(n, subject, size, angle, move, focal, duration, contents):
    assert len(contents) == 11
    title = f'【shot {n}｜{subject}｜{size}｜{angle}｜{move}｜焦段（Focal Length）：{focal}｜duration: {duration:.1f}s】'
    return title + '\n' + '\n'.join(f'{label}：{content}' for label, content in zip(labels, contents))

