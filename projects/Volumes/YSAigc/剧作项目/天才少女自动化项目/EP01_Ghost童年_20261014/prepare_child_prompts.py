prompts = {}
anchors = {}

def add(code, prompt, bindings, seconds, intended, description):
    assert len(prompt) < 5000, (code, len(prompt))
    for binding in bindings:
        assert prompt.count(binding['anchor']) == 1, (code, binding)
    blocks = prompt.split('【shot ')[1:]
    for block in blocks:
        offsets = [block.index(label+'：') for label in labels]
        assert offsets == sorted(offsets)
    assert FIXED in prompt
    BASE.joinpath(code+'.txt').write_text(prompt + '\n', encoding='utf-8')
    anchors[code] = {'file':code+'.txt','chars':len(prompt)+1,'generation_seconds':seconds,'approved_cut_seconds':intended,'description':description,'model':'九梦2.0 Pro','resolution':'720P','bindings':bindings}
    prompts[code] = prompt

def binding(anchor, filename, category):
    return {'anchor':anchor,'filename':filename,'category':category}

