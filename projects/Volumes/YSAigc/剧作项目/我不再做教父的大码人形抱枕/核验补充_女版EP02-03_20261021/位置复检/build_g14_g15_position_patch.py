def fld(n, shot, label):
    t = texts[n]
    if not shot:
        a = t.index('场景：')
        return t[a:t.index('以下所有Shot', a)].rstrip()
    m = re.search(rf'^Shot{shot:02}:', t, re.M)
    assert m
    st = m.end()
    nxt = re.search(r'^Shot\d+:', t[st:], re.M)
    en = st + nxt.start() if nxt else len(t)
    s = t[st:en]
    a = re.search(rf'^{label}：', s, re.M)
    assert a
    b = re.search(r'^(?:' + '|'.join(labels) + r')：', s[a.end():], re.M)
    return s[a.start():a.end()+b.start() if b else len(s)].rstrip()

def add(n, shot, label, new, reason):
    old = fld(n,shot,label)
    new = new(old) if callable(new) else new
    assert old != new
    assert texts[n].count(old) == 1
    assert (n,shot,label) not in seen
    seen.add((n,shot,label))
    out.append(dict(group=f'G{n:02}',old=old,new=new,reason=f'Shot{shot:02} {reason}' if shot else reason))

def sub(*pairs):
    def fn(s):
        for a,b in pairs:
            assert s.count(a)==1,(a,s)
            s=s.replace(a,b)
        return s
    return fn

